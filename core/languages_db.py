def get_language(code: str):
    code_clean = code.strip().lower()
    if "-" in code_clean:
        prefix = code_clean.split("-")[0]
        if prefix in LANGUAGES:
            return LANGUAGES[prefix]
    if code_clean in LANGUAGES:
        return LANGUAGES[code_clean]
    for k, v in LANGUAGES.items():
        if v.get("iso3") == code_clean:
            return v
        if v.get("name", "").lower() == code_clean:
            return v
    return None


def get_all_languages_list():
    return sorted(list(LANGUAGES.values()), key=lambda x: x["name"])


def search_languages(query: str) -> list[dict]:
    """Search languages by name, code, native name, script, or region."""
    if not query:
        return get_all_languages_list()
    q = query.strip().lower()
    matches = []
    for lang in LANGUAGES.values():
        if (
            q in lang["name"].lower()
            or q in lang["code"].lower()
            or q in lang.get("iso3", "").lower()
            or q in lang.get("native_name", "").lower()
            or q in lang.get("script", "").lower()
            or q in lang.get("family", "").lower()
            or q in lang.get("region", "").lower()
        ):
            matches.append(lang)
    return sorted(matches, key=lambda x: x["name"])
